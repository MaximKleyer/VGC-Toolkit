"""Damage engine tests.

The core verification is roll parity with reference fixtures generated by
@smogon/calc (the engine behind the NCP Champions calculator), using identical
stat/type/move inputs from our own pokedex — so any failure is a mechanics bug,
not a data difference. Champions uses the standard 16 damage rolls (85..100),
so fixtures store the full 16-roll reference array and the test compares against
it directly.
"""

import json
from pathlib import Path

import pytest

from vgc_toolkit.core import damage
from vgc_toolkit.core.damage import Combatant, Field, calculate, describe
from vgc_toolkit.core.stats import SPSpread

FIXTURES = json.loads(
    (Path(__file__).parent / "fixtures_damage.json").read_text())


def _combatant(pokemon_id: str, opts: dict) -> Combatant:
    status_map = {"brn": "burn", "par": "paralysis", "": None}
    return Combatant(
        pokemon_id=pokemon_id,
        spread=SPSpread.from_dict(opts.get("sp", {})),
        alignment=opts.get("nature", "Serious"),
        ability=opts.get("ability", "Pressure"),  # fixtures' neutral default
        item=opts.get("item"),
        stages=opts.get("boosts", {}),
        status=status_map.get(opts.get("status", ""), opts.get("status")),
    )


def _field(case: dict) -> Field:
    f, m = case.get("field", {}), case.get("move_opts", {})
    return Field(
        weather=(f.get("weather") or "none").lower(),
        terrain=(f.get("terrain") or "none").lower(),
        is_spread=True if m.get("spread") else None,
        is_crit=bool(m.get("crit")),
        reflect=bool(f.get("reflect")),
        light_screen=bool(f.get("lightScreen")),
        friend_guard=bool(f.get("friendGuard")),
        helping_hand=bool(f.get("helpingHand")),
    )


class TestReferenceParity:
    @pytest.mark.parametrize("case", FIXTURES, ids=[c["label"] for c in FIXTURES])
    def test_rolls_match_reference(self, case):
        result = calculate(
            _combatant(case["attacker"], case["attacker_opts"]),
            _combatant(case["defender"], case["defender_opts"]),
            case["move"],
            _field(case),
        )
        # Champions uses the standard 16 rolls (85..100); fixtures store the
        # full 16-roll reference array, so compare against it directly.
        expected = case["expected_rolls"]
        assert result["rolls"] == expected, (
            f"{case['label']}: {result['rolls']} != {expected}")


class TestEngineBehavior:
    def test_immunity_by_type(self):
        r = calculate(Combatant("golurk-mega", ability="Iron Fist"),
                      Combatant("dragonite-mega", ability="Multiscale"),
                      "Earthquake")
        assert r["rolls"] == [0] * 16
        assert any("immune" in n for n in r["notes"])

    def test_immunity_by_ability(self):
        r = calculate(Combatant("primarina", ability="Torrent"),
                      Combatant("politoed", ability="Water Absorb"), "Surf")
        assert r["rolls"] == [0] * 16

    def test_status_moves_deal_zero(self):
        r = calculate(Combatant("clefable"), Combatant("kingambit"), "Thunder Wave")
        assert r["rolls"] == [0] * 16

    def test_mega_sol_no_longer_flagged_unknown(self):
        r = calculate(Combatant("meganium-mega", ability="Mega Sol",
                                spread=SPSpread(spa=32)),
                      Combatant("kingambit"), "Moonblast")
        assert not any("unknown" in n.lower() for n in r["notes"])

    def test_variable_bp_flagged_and_overridable(self):
        base = calculate(Combatant("kingambit"), Combatant("clefable"), "Gyro Ball")
        assert any("variable base power" in n for n in base["notes"])
        overridden = calculate(Combatant("kingambit"), Combatant("clefable"),
                               "Gyro Ball", bp_override=120)
        assert max(overridden["rolls"]) > max(base["rolls"])

    def test_weight_based_moves_use_pokedex_weights(self):
        def bp(att, dfn, move, atk_ability=None, def_ability=None):
            return calculate(Combatant(att, ability=atk_ability),
                             Combatant(dfn, ability=def_ability), move)["base_power"]
        # Low Kick / Grass Knot: the target's weight (Pikachu 6 kg, Clefable 40 kg, Snorlax 460 kg).
        assert bp("kingambit", "pikachu", "Low Kick") == 20
        assert bp("kingambit", "clefable", "Low Kick") == 60
        assert bp("kingambit", "snorlax", "Low Kick") == 120
        assert bp("venusaur", "snorlax", "Grass Knot") == 120
        r = calculate(Combatant("kingambit"), Combatant("snorlax"), "Low Kick")
        assert any("120 BP" in n and "460" in n for n in r["notes"])
        assert not any("variable base power" in n for n in r["notes"])
        assert calculate(Combatant("kingambit"), Combatant("snorlax"), "Low Kick",
                         bp_override=40)["base_power"] == 40
        # Heavy Slam / Heat Crash: user weight over target weight (460 / 6 -> 120; equal -> 40).
        assert bp("snorlax", "pikachu", "Heavy Slam") == 120
        assert bp("snorlax", "snorlax", "Heavy Slam") == 40
        # Light Metal halves the holder: Metagross 550 kg -> 275 kg over Kingambit's 120 kg (4.6 -> 100, 2.3 -> 60).
        assert bp("metagross", "kingambit", "Heavy Slam", atk_ability="Clear Body") == 100
        assert bp("metagross", "kingambit", "Heavy Slam", atk_ability="Light Metal") == 60
        # ... and as a target: Grass Knot into a Light Metal Scizor (118 -> 59 kg) drops from 100 to 80.
        assert bp("venusaur", "scizor", "Grass Knot", def_ability="Technician") == 100
        assert bp("venusaur", "scizor", "Grass Knot", def_ability="Light Metal") == 80
        # Heavy Metal doubles: Aggron 360 kg over Kingambit 120 kg is 3.0 -> 80, 720 kg is 6.0 -> 120.
        assert bp("aggron", "kingambit", "Heavy Slam", atk_ability="Sturdy") == 80
        assert bp("aggron", "kingambit", "Heavy Slam", atk_ability="Heavy Metal") == 120

    def test_ko_chance_sanity(self):
        # A hit dealing 50-60% must be a guaranteed 2HKO and 0% OHKO.
        rolls = [110 + i for i in range(16)]  # vs 200 HP
        ko = damage._ko_chance(rolls, 200)
        assert "1hko" not in ko or ko["1hko"] == 0
        assert ko["2hko"] == 100.0

    def test_guaranteed_ohko_reads_100(self):
        # Regression: a hit lethal on every roll must report a guaranteed OHKO
        # (100.0) through the real engine — not 93.8% — and must not emit
        # phantom follow-up KO rows. Previously masked by a 15-roll-over-/16 bug.
        a = Combatant("kingambit", spread=SPSpread(atk=32), alignment="Adamant")
        d = Combatant("clefable", current_hp_fraction=0.1)  # chipped: every roll kills
        r = calculate(a, d, "Iron Head")
        assert min(r["rolls"]) > r["defender_current_hp"]   # confirm every roll lethal
        assert r["ko_chances"]["1hko"] == 100.0
        assert "2hko" not in r["ko_chances"]                # early-exit fired

    def test_describe_format(self):
        a = Combatant("chandelure-mega", spread=SPSpread(spa=32),
                      alignment="Modest")
        d = Combatant("kingambit", spread=SPSpread(hp=32))
        r = calculate(a, d, "Heat Wave")
        s = describe(a, d, r)
        assert "Mega Chandelure" in s and "Heat Wave" in s and "%" in s


class TestChampionsAbilities:
    def test_dragonize_converts_and_boosts(self):
        plain = calculate(Combatant("feraligatr-mega", ability="Torrent",
                                    spread=SPSpread(atk=32), alignment="Adamant"),
                          Combatant("dragapult"), "Double-Edge")
        drag = calculate(Combatant("feraligatr-mega", ability="Dragonize",
                                   spread=SPSpread(atk=32), alignment="Adamant"),
                         Combatant("dragapult"), "Double-Edge")
        # Normal -> Dragon: gains 2x vs Dragapult, x1.2 power, and Dragon STAB
        assert drag["type_effectiveness"] == 2.0
        assert plain["type_effectiveness"] == 1.0
        assert min(drag["rolls"]) > min(plain["rolls"]) * 2

    def test_mega_sol_sun_boost_without_weather(self):
        # Fire move from a Mega Sol user is x1.5 with no weather set
        plain_fire = calculate(Combatant("clefable", spread=SPSpread(spa=32)),
                               Combatant("kingambit"), "Mystical Fire")
        sol_fire = calculate(Combatant("clefable", ability="Mega Sol",
                                       spread=SPSpread(spa=32)),
                             Combatant("kingambit"), "Mystical Fire")
        assert min(sol_fire["rolls"]) > min(plain_fire["rolls"]) * 1.4

    def test_piercing_drill_through_protect(self):
        blocked = calculate(Combatant("excadrill-mega", ability="Sand Force",
                                      spread=SPSpread(atk=32)),
                            Combatant("kingambit"), "Iron Head",
                            Field(defender_protected=True))
        pierced = calculate(Combatant("excadrill-mega", ability="Piercing Drill",
                                      spread=SPSpread(atk=32)),
                            Combatant("kingambit"), "Iron Head",
                            Field(defender_protected=True))
        full = calculate(Combatant("excadrill-mega", ability="Piercing Drill",
                                   spread=SPSpread(atk=32)),
                         Combatant("kingambit"), "Iron Head")
        assert blocked["rolls"] == [0] * 16
        import math
        assert 0 < max(pierced["rolls"]) <= math.ceil(max(full["rolls"]) * 0.27)

    def test_spicy_spray_notes_burn(self):
        r = calculate(Combatant("kingambit", spread=SPSpread(atk=32)),
                      Combatant("scovillain-mega", ability="Spicy Spray"),
                      "Kowtow Cleave")
        assert any("Spicy Spray" in n for n in r["notes"])
        assert max(r["rolls"]) > 0



class TestFieldMechanics:
    def test_fairy_aura(self):
        plain = calculate(Combatant("clefable", spread=SPSpread(spa=32)),
                          Combatant("kingambit"), "Moonblast")
        aura = calculate(Combatant("clefable", spread=SPSpread(spa=32)),
                         Combatant("kingambit"), "Moonblast",
                         Field(fairy_aura=True))
        ratio = min(aura["rolls"]) / min(plain["rolls"])
        assert 1.28 < ratio < 1.38

    def test_gravity_grounds_flying_and_levitate(self):
        atk = Combatant("golurk-mega", spread=SPSpread(atk=32), ability="Iron Fist")
        flying = Combatant("skarmory-mega")
        r = calculate(atk, flying, "Earthquake", Field(gravity=True))
        assert max(r["rolls"]) > 0
        assert r["type_effectiveness"] == 2.0  # Steel 2x, Flying grounded by gravity
        lev = Combatant("chandelure-mega", ability="Levitate")
        r2 = calculate(atk, lev, "Earthquake", Field(gravity=True))
        assert max(r2["rolls"]) > 0

    def test_singles_screens_halve(self):
        atk = Combatant("kingambit", spread=SPSpread(atk=32))
        dfn = Combatant("clefable", spread=SPSpread(hp=32))
        dbl = calculate(atk, dfn, "Iron Head", Field(reflect=True))
        sgl = calculate(atk, dfn, "Iron Head",
                        Field(reflect=True, is_doubles=False))
        assert min(sgl["rolls"]) < min(dbl["rolls"])


